<?php

namespace App\Console\Commands;

use App\Support\Luma\OtherServicesKnowledge as K;
use Illuminate\Console\Command;

/** Writes docs/luma-knowledge-map.md from the knowledge nodes, so the document and the code can never disagree. */
class LumaKnowledgeMap extends Command
{
    protected $signature = 'luma:knowledge-map';

    protected $description = "Regenerate docs/luma-knowledge-map.md from Luma's Other Services knowledge (no database access).";

    public function handle(): int
    {
        $nodes  = K::nodes();
        $titles = K::titles();
        $out    = [];

        $out[] = '# Luma knowledge map: Other Services';
        $out[] = '';
        $out[] = 'Generated by `php artisan luma:knowledge-map` from `app/Support/Luma/OtherServicesKnowledge.php`. Do not edit by hand: change the PHP file and regenerate.';
        $out[] = '';
        $out[] = 'Every node below becomes an intent named `id` through `php artisan chatbot:sync-defaults` (insert-only: an intent that already exists is never changed, so edits made in Admin > Chatbot are safe). The follow-up buttons are chips: tapping one sends its title as the next message, which reaches the child node. A node marked **handler** reads the signed-in customer\'s own data (guests get the general answer and a Log in button) or starts the guided flow. A node marked **contact card** also shows the shop\'s phone and email from Contact Settings. `{{tokens}}` are filled from config and Contact Settings, never typed in.';
        $out[] = '';
        $out[] = 'Tone: calm, never defensive, short sentences, plain words, "po" in Tagalog, apologise once, never blame the customer, never promise a refund or a date, never say "approved" or "guaranteed". See `docs/luma-tone-rules.md`.';
        $out[] = '';
        $out[] = '## Tree';
        $out[] = '';

        foreach (K::BRANCHES as $b => $name) {
            $out[] = "### {$b}. {$name}";
            $out[] = '';
            $ids = array_keys(array_filter($nodes, fn ($n) => $n['b'] === $b));
            if ($b === 11) {
                $out[] = 'No new node: contact, hours and "talk to a real person" are answered by the existing defaults `luma_contact_shop` and `luma_shop_open` (phone, email and hours from Contact Settings, with the contact card). Every fallback also offers a **Talk to a person** chip, and after two misses in a row the contact card.';
                $out[] = '';
                continue;
            }
            if ($b === 14) {
                $out[] = 'No intent row: this is code (`App\Support\Luma\Disambiguation`). A bare **refund**, **cancel**, **payment**, **gcash**, **cash** or **bayad** with no context gets one question: *"Is this about an Other Services job (repair or labor) or a custom furniture order?"* with two chips. The answer is remembered for the conversation (30 minutes), so a follow-up like "and refund?" is not asked again. Other Services job -> the Other Services answer or the guided refund flow. Custom furniture order -> the existing `luma_cancel_refund` / `luma_payment_methods` answers, untouched.';
                $out[] = '';
                continue;
            }
            foreach ($ids as $id) {
                $n = $nodes[$id];
                $out[] = "#### `{$id}`: {$n['title']}";
                $out[] = '';
                $flags = [];
                if (!empty($n['handler'])) {
                    $flags[] = '**handler:** `' . $n['handler'] . '`';
                }
                if (!empty($n['card'])) {
                    $flags[] = '**contact card**';
                }
                if ($flags) {
                    $out[] = implode(' · ', $flags);
                    $out[] = '';
                }
                $out[] = "Tagalog title: {$n['title_tl']}";
                $out[] = '';
                foreach (['en' => 'English', 'tl' => 'Tagalog', 'mix' => 'Taglish'] as $k => $label) {
                    $out[] = "*Example phrasings, {$label}:*";
                    foreach ($n['say'][$k] as $s) {
                        $out[] = "- {$s}";
                    }
                    $out[] = '';
                }
                $out[] = '**Answer (English):** ' . $n['en'];
                $out[] = '';
                $out[] = '**Answer (Tagalog):** ' . $n['tl'];
                $out[] = '';
                $next = array_map(fn ($c) => "`{$c}` ({$titles[$c]['en']})", $n['next'] ?? []);
                $out[] = '**Follow-up buttons:** ' . ($next ? implode(', ', $next) : 'none');
                if (!empty($n['buttons'])) {
                    $out[] = '';
                    $out[] = '**Link buttons:** ' . implode(', ', array_map(fn ($b) => "{$b[0]} -> `{$b[2]}`", $n['buttons']));
                }
                $out[] = '';
            }
        }

        $path = base_path('docs/luma-knowledge-map.md');
        file_put_contents($path, implode("\n", $out) . "\n");
        $this->info('Wrote ' . $path . ' (' . count($nodes) . ' nodes).');

        return self::SUCCESS;
    }
}
